const FeePayment = require("../models/feePayment.model");
const FeeSetting = require("../models/feeSetting.model");
const Student = require("../models/student.model");
let currentMonthFeeGeneration = null;

const MONTHLY_FEE_CLASSES = [
    "Primary", "00", "01", "02", "03", "04", "05", "Advance",
    "06", "07", "08", "09", "10", "Balegan"
];

function getCurrentBillingMonth() {
    const parts = new Intl.DateTimeFormat("en", {
        timeZone: "Asia/Kolkata",
        year: "numeric",
        month: "2-digit"
    }).formatToParts(new Date());
    const year = parts.find((part) => part.type === "year").value;
    const month = parts.find((part) => part.type === "month").value;
    return `${year}-${month}`;
}

function getMonthStartDate(month) {
    if (!/^\d{4}-\d{2}$/.test(month || "")) return new Date();
    // Use noon in India so the stored date remains the first in date inputs
    // across UTC and Asia/Kolkata conversions.
    return new Date(`${month}-01T12:00:00+05:30`);
}

async function ensureCurrentMonthPendingFees() {
    if (currentMonthFeeGeneration) return currentMonthFeeGeneration;

    currentMonthFeeGeneration = (async () => {
        const month = getCurrentBillingMonth();
        const feeSettings = await FeeSetting.findOne({ key: "monthly-fees" }).lean();
        const configuredAmounts = new Map(
            (feeSettings?.classAmounts || []).map((item) => [item.className, item.amount])
        );
        const activeStudents = await Student.find({ status: "active" }).select("_id preferredCourseClass");
        if (!activeStudents.length) return;

        const existingMonthlyFees = await FeePayment.find({
            student: { $in: activeStudents.map((student) => student._id) },
            feeType: "monthly",
            month
        }).select("student amount status autoGenerated note");
        const feesByStudent = new Map(
            existingMonthlyFees.map((fee) => [fee.student.toString(), fee])
        );

        for (const student of activeStudents) {
            const studentId = student._id.toString();
            const configuredAmount = Number(
                configuredAmounts.get(student.preferredCourseClass) || 0
            );
            const existingFee = feesByStudent.get(studentId);

            if (existingFee) {
                const legacyGeneratedFee = existingFee.note?.startsWith("Auto-generated monthly fee.");
                if (
                    existingFee.status === "pending" &&
                    (existingFee.autoGenerated || legacyGeneratedFee) &&
                    existingFee.amount !== configuredAmount
                ) {
                    await FeePayment.updateOne(
                        { _id: existingFee._id },
                        { $set: { amount: configuredAmount, autoGenerated: true } }
                    );
                }
                continue;
            }

            await FeePayment.create({
                student: student._id,
                feeType: "monthly",
                amount: configuredAmount,
                month,
                paymentDate: getMonthStartDate(month),
                paymentMethod: "cash",
                status: "pending",
                autoGenerated: true,
                note: "Auto-generated monthly fee. Enter the fee amount when updating this record."
            });
        }
    })();

    try {
        await currentMonthFeeGeneration;
    } finally {
        currentMonthFeeGeneration = null;
    }
}

async function getMonthlyFeeSettings(req, res) {
    try {
        const settings = await FeeSetting.findOne({ key: "monthly-fees" }).lean();
        return res.status(200).json({
            classAmounts: settings?.classAmounts || []
        });
    } catch (error) {
        console.error("Get monthly fee settings error:", error);
        return res.status(500).json({ message: "Internal server error" });
    }
}

async function updateMonthlyFeeSettings(req, res) {
    try {
        const { classAmounts } = req.body;
        if (!Array.isArray(classAmounts)) {
            return res.status(400).json({ message: "Class-wise fee amounts are required." });
        }

        const normalizedAmounts = [];
        const seenClasses = new Set();
        for (const item of classAmounts) {
            if (!item || !MONTHLY_FEE_CLASSES.includes(item.className)) {
                return res.status(400).json({ message: "Invalid class in fee settings." });
            }
            const amount = Number(item.amount);
            if (!Number.isFinite(amount) || amount < 0) {
                return res.status(400).json({ message: "Fee amount must be zero or greater." });
            }
            if (seenClasses.has(item.className)) continue;
            seenClasses.add(item.className);
            normalizedAmounts.push({ className: item.className, amount });
        }

        const settings = await FeeSetting.findOneAndUpdate(
            { key: "monthly-fees" },
            { $set: { classAmounts: normalizedAmounts } },
            { new: true, upsert: true, runValidators: true, setDefaultsOnInsert: true }
        );

        return res.status(200).json({
            message: "Monthly fee settings saved successfully.",
            classAmounts: settings.classAmounts
        });
    } catch (error) {
        console.error("Update monthly fee settings error:", error);
        return res.status(500).json({ message: "Internal server error" });
    }
}


// Create Fee Payment
async function createFeePayment(req, res) {
    try {
        const {
            student,
            feeType,
            amount,
            month,
            exam,
            paymentDate,
            paymentMethod,
            status,
            note
        } = req.body;

        const studentExists = await Student.findById(student);

        if (!studentExists) {
            return res.status(404).json({
                message: "Student not found"
            });
        }

        if (feeType === "monthly") {
            if (studentExists.status !== "active") {
                return res.status(400).json({
                    message: "Monthly fee records can only be created for active students."
                });
            }

            const existingMonthlyFee = await FeePayment.findOne({
                student,
                feeType: "monthly",
                month
            });

            if (existingMonthlyFee) {
                return res.status(409).json({
                    message: "A monthly fee record already exists for this student and month. Please update that record instead."
                });
            }
        }

        const feePayment = await FeePayment.create({
            student,
            feeType,
            amount,
            month,
            exam,
            paymentDate: feeType === "monthly" && status === "pending"
                ? getMonthStartDate(month)
                : paymentDate,
            paymentMethod,
            status,
            note
        });

await feePayment.populate(
    "student",
    "name fatherName phone rollNo"
);

        return res.status(201).json({
            message: "Fee payment recorded successfully",
            feePayment
        });

    } catch (error) {
        console.error("Create fee payment error:", error);

        return res.status(500).json({
            message: "Internal server error"
        });
    }
}


// Get All Fee Payments
async function getFeePayments(req, res) {
    try {
        await ensureCurrentMonthPendingFees();

        const feePayments = await FeePayment.find()
            .populate("student", "name fatherName phone rollNo")
            .sort({ createdAt: -1 });

        return res.status(200).json({
            feePayments
        });

    } catch (error) {
        console.error("Get fee payments error:", error);

        return res.status(500).json({
            message: "Internal server error"
        });
    }
}


