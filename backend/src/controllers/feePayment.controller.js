// Update Fee Payment
async function updateFeePayment(req, res) {
    try {
        const {
            feeType,
            amount,
            month,
            exam,
            paymentDate,
            paymentMethod,
            status,
            note
        } = req.body;

        const existingPayment = await FeePayment.findById(req.params.id).select("status");
        if (!existingPayment) {
            return res.status(404).json({ message: "Fee payment not found" });
        }

        const updateData = {};

        if (feeType !== undefined) {
            updateData.feeType = feeType;
        }

        if (amount !== undefined) {
            updateData.amount = amount;
        }

        if (month !== undefined) {
            updateData.month = month;
        }

        if (exam !== undefined) {
            updateData.exam = exam;
        }

        if (paymentDate !== undefined) {
            updateData.paymentDate = paymentDate;
        }

        if (paymentMethod !== undefined) {
            updateData.paymentMethod = paymentMethod;
        }

        if (status !== undefined) {
            updateData.status = status;
            if (status === "paid" && existingPayment.status !== "paid") {
                updateData.paymentDate = new Date();
            } else if (status === "pending" && (month || req.body.month)) {
                updateData.paymentDate = getMonthStartDate(month || req.body.month);
            }
        }

        if (note !== undefined) {
            updateData.note = note;
        }

        updateData.autoGenerated = false;

        const feePayment = await FeePayment.findByIdAndUpdate(
            req.params.id,
            updateData,
            {
                new: true,
                runValidators: true
            }
        ).populate("student", "name fatherName phone rollNo");

        if (!feePayment) {
            return res.status(404).json({
                message: "Fee payment not found"
            });
        }

        return res.status(200).json({
            message: "Fee payment updated successfully",
            feePayment
        });

    } catch (error) {
        console.error("Update fee payment error:", error);

        return res.status(500).json({
            message: "Internal server error"
        });
    }
}


